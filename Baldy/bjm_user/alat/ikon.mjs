// Membuat bjm_user.Client/Komponen/Ikon.g.cs: data SVG ikon Font Awesome Free (gaya solid) yang dipakai SIKOTIS.
//
// Menambah ikon: cari di https://fontawesome.com/search?ic=free-collection, tambahkan namanya ke DAFTAR
// (huruf kecil, pakai tanda hubung seperti di situs Font Awesome), lalu jalankan:
//   npm install        (sekali saja, di folder alat)
//   npm run ikon
// Folder node_modules lain bisa dipakai lewat variabel SIKOTIS_NODE_MODULES.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const sini = dirname(fileURLToPath(import.meta.url))
const modul = process.env.SIKOTIS_NODE_MODULES ?? join(sini, 'node_modules')
const require = createRequire(join(modul, 'x.js'))
const fa = require('@fortawesome/free-solid-svg-icons')
const versi = require('@fortawesome/free-solid-svg-icons/package.json').version

const DAFTAR = `
arrow-down arrow-left arrow-right arrows-rotate arrow-trend-down arrow-trend-up arrow-up ban bars bed building
calendar-days chart-line check check-double chevron-down chevron-left chevron-right circle-check circle-exclamation
circle-info circle-notch circle-question clipboard-check clock-rotate-left compass database download ellipsis eye
eye-slash file-arrow-down file-arrow-up file-contract file-export file-invoice-dollar file-lines filter flag-checkered
floppy-disk folder-open gas-pump gauge-high hand-holding-dollar handshake hashtag image inbox key link list-check
location-dot lock lock-open magnifying-glass magnifying-glass-minus map-location-dot minus mug-hot paper-plane pen
percent plus print receipt right-from-bracket right-to-bracket rotate-left route sack-dollar scissors
screwdriver-wrench shield-halved ship sort trash-can triangle-exclamation truck truck-fast truck-ramp-box user
user-plus users users-gear wallet wand-magic-sparkles warehouse xmark
`.trim().split(/\s+/)

const pascal = (nama) => nama.replace(/(^|-)(\w)/g, (_, _s, c) => c.toUpperCase())
const baris = DAFTAR.map((nama) => {
  const def = fa[`fa${pascal(nama)}`]
  if (!def) throw new Error(`Ikon "${nama}" tidak ada di Font Awesome Free (solid).`)
  const [lebar, tinggi, , , path] = def.icon
  return `    public static readonly IkonDef ${pascal(nama)} = new("${nama}", ${lebar}, ${tinggi}, "${path}");`
})

const isi = `// <auto-generated>
// Dibuat oleh alat/ikon.mjs dari @fortawesome/free-solid-svg-icons ${versi} (Font Awesome Free, ikon berlisensi CC BY 4.0).
// Jangan diubah langsung: tambahkan nama ikon di alat/ikon.mjs lalu jalankan "npm run ikon".
// </auto-generated>
namespace bjm_user.Client.Komponen;

public static partial class Ikon
{
${baris.join('\n')}
}
`
const tujuan = join(sini, '..', 'bjm_user.Client', 'Komponen', 'Ikon.g.cs')
writeFileSync(tujuan, isi)
console.log(`${DAFTAR.length} ikon ditulis ke ${tujuan}`)
